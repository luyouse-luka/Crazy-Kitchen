// Handwritten cards → the identity/lines table the game reads. Orders stay rolled by
// customer.ts (the card's order line would contradict the rolled spec), so only these ship.
import { readFileSync, writeFileSync } from 'node:fs'

const cards = JSON.parse(readFileSync('pipeline/handwritten/cards.json', 'utf8'))
const banter = JSON.parse(readFileSync('pipeline/handwritten/banter.json', 'utf8'))
if (banter.cards.length !== cards.length || cards.some(c => !banter.cards.some(b => b.id === c.id))) throw new Error('Banter card IDs must match customer cards')
for (const c of banter.cards) for (const [key, min] of [['back', 4], ['complain', 2], ['exit', 2]]) {
  if (new Set(c[key]).size < min || c[key].some(s => !s.trim() || s.length > 40)) throw new Error(`Invalid banter: ${c.id}.${key}`)
}
writeFileSync('game/assets/logic/banterLines.ts', '// Generated by `pnpm cards:export` from pipeline/handwritten/banter.json — do not edit.\nexport const BANTER = ' + JSON.stringify({ ...banter, cards: cards.map(c => banter.cards.find(b => b.id === c.id)) }, null, 2) + ' as const\n')
const rows = cards.map((c) => ({
  identity: c.identity,
  greet: c.lines.greet,
  wait_nudge: c.lines.wait_nudge,
  praise: c.lines.praise,
  complain: c.lines.complain,
  argue: c.lines.argue,
}))
const out =
  '// Generated by `pnpm cards:export` from pipeline/handwritten/cards.json — do not edit.\n' +
  'export interface CardLines {\n  identity: string\n  greet: string\n  wait_nudge: string\n  praise: string\n  complain: string\n  /** Three comebacks, then the storm-off line */\n  argue: readonly string[]\n}\n\n' +
  `export const CARD_LINES: readonly CardLines[] = ${JSON.stringify(rows, null, 2)}\n`
writeFileSync('game/assets/scripts/cardLines.ts', out)
console.log(`cardLines.ts: ${rows.length} cards`)
